// Regenerates the in-game icon tables for both builds from Iconify:
//   node tools/gen-icons.mjs
// writes  app/.../ui/components/GameIcons.kt  and  web/js/icons.js
// Icons are Phosphor "fill" (MIT) unless the id names another set as "set:name"; those are scaled
// into Phosphor's 256x256 viewBox so every path shares it. Add an icon by adding a line to ICONS below.
// Check the set's license before using another set, and list it in NOTICE.md.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// [Kotlin enum name, JS key, Phosphor icon id]
const ICONS = [
  // Stamina refill pickup and HUD label. Phosphor has no water bottle; Material Symbols is Apache 2.0.
  ['WATER_BOTTLE', 'waterBottle', 'material-symbols:water-bottle'],
  ['SHIELD', 'shield', 'shield-star-fill'],
  ['MAGNET', 'magnet', 'magnet-fill'],
  ['PAUSE', 'pause', 'pause-fill'],
  ['CARET_UP', 'caretUp', 'caret-up-fill'],
  ['CARET_DOWN', 'caretDown', 'caret-down-fill'],
  ['CARET_LEFT', 'caretLeft', 'caret-left-fill'],
  ['CARET_RIGHT', 'caretRight', 'caret-right-fill'],
  ['GAUGE', 'gauge', 'gauge-fill'],
  ['SHARE', 'share', 'share-network-fill'],
  ['TROPHY', 'trophy', 'trophy-fill'],
  ['RANKING', 'ranking', 'ranking-fill'],
  ['VIBRATE', 'vibrate', 'vibrate-fill'],
  ['GEAR', 'gear', 'gear-fill'],
  ['HOME', 'home', 'house-fill'],
  ['PLAY', 'play', 'play-fill'],
  ['RETRY', 'retry', 'arrow-clockwise-fill'],
  ['PLAY_CIRCLE', 'playCircle', 'play-circle-fill'],
  // Related apps: a card row opens another app or its store page; the game-over link to the sibling racing game.
  ['OPEN_EXTERNAL', 'openExternal', 'arrow-square-out-fill'],
  ['FLAG_CHECKERED', 'flagCheckered', 'flag-checkered-fill'],
];

const VIEWBOX = 256;
const split = (id) => (id.includes(':') ? id.split(':') : ['ph', id]);
const sets = {};
for (const [, , id] of ICONS) {
  const [set, name] = split(id);
  (sets[set] ||= []).push(name);
}
for (const [set, names] of Object.entries(sets)) {
  sets[set] = await (await fetch(`https://api.iconify.design/${set}.json?icons=${names.join(',')}`)).json();
}

/** Multiplies every number in a path by k: right for absolute and relative commands alike, but not arcs. */
function scalePath(d, k) {
  if (/[aA]/.test(d)) throw new Error('cannot scale a path with arcs');
  // A number written right after another (".5.25") needs a separator once it is rewritten ("5.33 2.67").
  return d.replace(/-?(?:\d+\.?\d*|\.\d+)/g, (n, at) => {
    const v = String(Math.round(parseFloat(n) * k * 100) / 100);
    return at > 0 && /[\d.]/.test(d[at - 1]) && v[0] !== '-' ? ` ${v}` : v;
  });
}

const dOf = (id) => {
  const [set, name] = split(id);
  const j = sets[set];
  const icon = j.icons[name];
  const m = icon?.body.match(/^<path[^>]* d="([^"]+)"[^>]*\/>$/);
  if (!m) throw new Error(`icon ${id} is missing or is not a single <path>`);
  const w = icon.width ?? j.width ?? 16;
  const h = icon.height ?? j.height ?? 16;
  if (w !== h) throw new Error(`icon ${id} is not square`);
  return w === VIEWBOX ? m[1] : scalePath(m[1], VIEWBOX / w);
};
const label = (id) => (id.includes(':') ? id : `ph:${id}`);
const data = ICONS.map(([k, js, id]) => ({ k, js, id, d: dOf(id) }));

const kt = `package com.khcompany.yorijorirun.ui.components

import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.Path
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.drawscope.DrawScope
import androidx.compose.ui.graphics.drawscope.withTransform
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

// GENERATED by tools/gen-icons.mjs — do not edit by hand. Phosphor Icons (MIT) and others, see NOTICE.md.
// Every path is in Phosphor's 256x256 viewBox.
enum class GameIcon(val pathData: String) {
${data.map((x) => `    ${x.k}("${x.d}"), // ${label(x.id)}`).join('\n')}
    ;
}

private const val VIEWBOX = 256f
private val pathCache = HashMap<GameIcon, Path>()
private val vectorCache = HashMap<GameIcon, ImageVector>()

private fun GameIcon.path(): Path = pathCache.getOrPut(this) { PathParser().parsePathString(pathData).toPath() }

/** For Compose \`Icon(imageVector = ...)\` in HUD/buttons; tint it with the Icon's \`tint\`. */
val GameIcon.vector: ImageVector
    get() = vectorCache.getOrPut(this) {
        ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = VIEWBOX,
            viewportHeight = VIEWBOX,
        ).addPath(pathData = PathParser().parsePathString(pathData).toNodes(), fill = SolidColor(Color.Black)).build()
    }

/** Draws the glyph centered at [center], [size] px wide/tall, straight onto a canvas. */
fun DrawScope.drawGameIcon(icon: GameIcon, center: Offset, size: Float, color: Color) {
    val s = size / VIEWBOX
    withTransform({
        translate(center.x - size / 2f, center.y - size / 2f)
        scale(s, s, pivot = Offset.Zero)
    }) {
        drawPath(icon.path(), color)
    }
}
`;

const js = `// GENERATED by tools/gen-icons.mjs — do not edit by hand. Phosphor Icons (MIT) and others, see NOTICE.md.
// Every path is in Phosphor's 256x256 viewBox.
const ICON_PATHS = {
${data.map((x) => `  ${x.js}: '${x.d}', // ${label(x.id)}`).join('\n')}
};

const icon2d = {};
function iconPath2D(name) {
  return icon2d[name] || (icon2d[name] = new Path2D(ICON_PATHS[name]));
}

/** Inline SVG markup that inherits the surrounding text color. */
function iconSvg(name) {
  return '<svg class="ico" viewBox="0 0 256 256" aria-hidden="true"><path fill="currentColor" d="' + ICON_PATHS[name] + '"/></svg>';
}

/** Fills every <span data-icon="name"> with its glyph. */
function hydrateIcons(root) {
  (root || document).querySelectorAll('[data-icon]').forEach((el) => { el.innerHTML = iconSvg(el.dataset.icon); });
}

/** Draws the glyph centered at (cx, cy), \`size\` px wide/tall, straight onto a canvas. */
function drawIconGlyph(ctx, name, cx, cy, size, color) {
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(size / 256, size / 256);
  ctx.fillStyle = color;
  ctx.fill(iconPath2D(name));
  ctx.restore();
}
`;

fs.writeFileSync(path.join(root, 'app/src/main/java/com/khcompany/yorijorirun/ui/components/GameIcons.kt'), kt);
fs.writeFileSync(path.join(root, 'web/js/icons.js'), js);
console.log('wrote', data.length, 'icons');
